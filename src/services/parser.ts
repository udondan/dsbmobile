import type { SubstitutionEntry, SubstitutionPlan } from '../types.js';

/** Decode common HTML entities and trim whitespace. */
function decodeHtmlEntities(s: string): string {
  return (
    s
      .replaceAll('&nbsp;', ' ')
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      // Decode &amp; last so "&amp;lt;" becomes "&lt;", not "<".
      .replaceAll('&amp;', '&')
      .trim()
  );
}

/**
 * Strip all HTML tags and trim whitespace.
 * Leftover `<` from nested or unclosed fragments like `<scr<b>ipt>` are removed too, so no
 * tag can remain. A literal `<` in the text is encoded as `&lt;` and decoded afterwards.
 */
function stripHtmlTags(s: string): string {
  return s
    .replaceAll(/<[^<>]*>/g, '')
    .replaceAll('<', '')
    .trim();
}

/** Strip tags, then decode entities. */
function htmlToText(s: string): string {
  return decodeHtmlEntities(stripHtmlTags(s));
}

/**
 * Return the inner HTML of each element between `openTag` and the next `closeTag`.
 * Scans the input once, so malformed HTML without closing tags can't cause quadratic runtime.
 * Both regexes must have the global flag.
 */
function extractElements(html: string, openTag: RegExp, closeTag: RegExp): string[] {
  const elements: string[] = [];
  let position = 0;
  for (;;) {
    openTag.lastIndex = position;
    const open = openTag.exec(html);
    if (!open) break;
    const start = open.index + open[0].length;
    closeTag.lastIndex = start;
    const close = closeTag.exec(html);
    if (!close) break;
    elements.push(html.slice(start, close.index));
    position = close.index + close[0].length;
  }
  return elements;
}

/**
 * Extracts the plan date (e.g. "20.3.2026 Freitag (Seite 1 / 8)") and returns it as ISO date.
 */
function parsePlanDate(html: string): string {
  const titleMarker = 'class="mon_title">';
  const titleStart = html.indexOf(titleMarker);
  const titleEnd = titleStart === -1 ? -1 : html.indexOf('</div>', titleStart);
  const rawDate =
    titleEnd === -1 ? '' : htmlToText(html.slice(titleStart + titleMarker.length, titleEnd));
  const match = /^(\d{1,2})\.(\d{1,2})\.(\d{4})/.exec(rawDate);
  if (!match) {
    throw new Error(`Could not parse plan date from HTML: "${rawDate}"`);
  }
  return `${match[3]}-${match[2].padStart(2, '0')}-${match[1].padStart(2, '0')}`;
}

/**
 * Splits a field like "Original?Substitute" (or just "Substitute") into its two parts.
 */
function splitChange(field: string): [string, string] {
  if (!field.includes('?')) return ['', field];
  const [original = '', substitute = ''] = field.split('?', 2);
  return [original, substitute];
}

/** Builds an entry from a row: Art | Stunde | Vertreter | Fach | Raum | Text */
function toSubstitutionEntry(cells: string[], className: string): SubstitutionEntry {
  const [type = '', period = '', teacherField = '', subject = '', roomField = '', text = ''] =
    cells;
  const [originalTeacher, substituteTeacher] = splitChange(teacherField);
  const [originalRoom, substituteRoom] = splitChange(roomField);
  return {
    className,
    type,
    period,
    originalTeacher,
    substituteTeacher,
    subject,
    originalRoom,
    substituteRoom,
    text,
  };
}

/**
 * Parses the HTML content of a DSBmobile substitution plan page.
 * The HTML is generated by Untis and has a consistent structure.
 */
export function parseSubstitutionHtml(html: string, lastUpdated: string): SubstitutionPlan {
  const date = parsePlanDate(html);
  const entries: SubstitutionEntry[] = [];
  let currentClass = '';

  for (const rowHtml of extractElements(html, /<tr[^<>]*>/g, /<\/tr>/g)) {
    const cells = extractElements(rowHtml, /<t[dh][^<>]*>/g, /<\/t[dh]>/g).map((cell) =>
      htmlToText(cell),
    );

    // Class header row: single cell with class name (e.g. "10a  10a" or just "10a")
    if (cells.length === 1) {
      currentClass = cells[0].split(/\s+/, 1)[0];
    } else if (cells.length >= 5 && cells[0] !== 'Art') {
      // Everything else is a header row, an info row or empty
      entries.push(toSubstitutionEntry(cells, currentClass));
    }
  }

  return { date, lastUpdated, entries };
}

type Range = [number, number];

/**
 * Parses a period string like "3", "5 - 6" or "5-6" into a start/end pair.
 * Returns undefined for anything else.
 */
function parsePeriod(period: string): Range | undefined {
  const match = /^(\d+)(?:\s*-\s*(\d+))?$/.exec(period.trim());
  if (!match) return undefined;
  const start = Number(match[1]);
  const end = match[2] === undefined ? start : Number(match[2]);
  return start <= end ? [start, end] : undefined;
}

function formatPeriod([start, end]: Range): string {
  return start === end ? String(start) : `${String(start)} - ${String(end)}`;
}

interface Group {
  entry: SubstitutionEntry;
  ranges: Range[];
}

/** Key of everything but the period. */
function entryKey(entry: SubstitutionEntry): string {
  return JSON.stringify([
    entry.className,
    entry.type,
    entry.originalTeacher,
    entry.substituteTeacher,
    entry.subject,
    entry.originalRoom,
    entry.substituteRoom,
    entry.text,
  ]);
}

/** Sorts ranges and joins the ones that are consecutive or overlap. */
function mergeRanges(ranges: Range[]): Range[] {
  const merged: Range[] = [];
  ranges.sort((a, b) => a[0] - b[0]);
  for (const [start, end] of ranges) {
    const last = merged.at(-1);
    if (last && start <= last[1] + 1) {
      last[1] = Math.max(last[1], end);
    } else {
      merged.push([start, end]);
    }
  }
  return merged;
}

/**
 * Normalizes substitution entries: entries that are identical except for their period and
 * whose periods are consecutive (or overlap) are merged into a single entry with a range
 * (e.g. "3" and "4" become "3 - 4"). Ranges are always written as "start - end".
 * Entries with a period that is not a number or a range are kept unchanged.
 * Merged entries take the position of the first entry of their group.
 */
export function mergeConsecutivePeriods(entries: SubstitutionEntry[]): SubstitutionEntry[] {
  const groups = new Map<string, Group>();
  // An entry stays as is, a group is written at the position of its first entry
  const order: (SubstitutionEntry | Group)[] = [];

  for (const entry of entries) {
    const range = parsePeriod(entry.period);
    const key = entryKey(entry);
    const group = range && groups.get(key);
    if (!range) {
      order.push(entry);
    } else if (group) {
      group.ranges.push(range);
    } else {
      const created: Group = { entry, ranges: [range] };
      groups.set(key, created);
      order.push(created);
    }
  }

  return order.flatMap((item) =>
    'ranges' in item
      ? mergeRanges(item.ranges).map((range) => ({ ...item.entry, period: formatPeriod(range) }))
      : [item],
  );
}
